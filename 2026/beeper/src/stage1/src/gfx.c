int gfx_init(const struct device *display)
{
	struct display_capabilities caps;

	if (!device_is_ready(display)) {
		return -1;
	}

	gfx_display = display;
	display_get_capabilities(display, &caps);
	gfx_screen_width = caps.x_resolution;
	gfx_screen_height = caps.y_resolution;

	display_blanking_off(display);

	return 0;
}

int gfx_width(void)
{
	return gfx_screen_width;
}

int gfx_height(void)
{
	return gfx_screen_height;
}

static void fill_line_color(uint16_t *buf, uint16_t color, int width)
{
	for (int i = 0; i < width; i++) {
		buf[i] = color;
	}
}

void gfx_fill_rect(int x, int y, int w, int h, uint16_t color)
{
	struct display_buffer_descriptor desc;

	if (x < 0) { w += x; x = 0; }
	if (y < 0) { h += y; y = 0; }
	if (x + w > gfx_screen_width) { w = gfx_screen_width - x; }
	if (y + h > gfx_screen_height) { h = gfx_screen_height - y; }
	if (w <= 0 || h <= 0) return;

	fill_line_color(gfx_line_buffer, color, w);

	desc.buf_size = w * sizeof(uint16_t);
	desc.width = w;
	desc.height = 1;
	desc.pitch = w;

	for (int row = 0; row < h; row++) {
		display_write(gfx_display, x, y + row, &desc, gfx_line_buffer);
	}
}

void gfx_draw_rect(int x, int y, int w, int h, uint16_t color, int thickness)
{
	gfx_fill_rect(x, y, w, thickness, color);                /* Top */
	gfx_fill_rect(x, y + h - thickness, w, thickness, color); /* Bottom */
	gfx_fill_rect(x, y, thickness, h, color);                /* Left */
	gfx_fill_rect(x + w - thickness, y, thickness, h, color); /* Right */
}

void gfx_clear(uint16_t color)
{
	gfx_fill_rect(0, 0, gfx_screen_width, gfx_screen_height, color);
}

void gfx_fill_circle(int cx, int cy, int r, uint16_t color)
{
	struct display_buffer_descriptor desc;

	for (int dy = -r; dy <= r; dy++) {
		int half_width = 0;
		for (int dx = -r; dx <= r; dx++) {
			if (dx * dx + dy * dy <= r * r) {
				half_width = dx;
			}
		}
		if (half_width > 0) {
			int start_x = cx - half_width;
			int width = half_width * 2 + 1;

			if (start_x < 0) { width += start_x; start_x = 0; }
			if (start_x + width > gfx_screen_width) { width = gfx_screen_width - start_x; }
			if (cy + dy < 0 || cy + dy >= gfx_screen_height || width <= 0) continue;

			fill_line_color(gfx_line_buffer, color, width);
			desc.buf_size = width * sizeof(uint16_t);
			desc.width = width;
			desc.height = 1;
			desc.pitch = width;

			display_write(gfx_display, start_x, cy + dy, &desc, gfx_line_buffer);
		}
	}
}

void gfx_draw_circle(int cx, int cy, int r, uint16_t color, int thickness)
{
	for (int i = 0; i < thickness; i++) {
		int cr = r - i;
		if (cr <= 0) break;

		/* Midpoint circle algorithm */
		int x = cr;
		int y = 0;
		int err = 0;

		while (x >= y) {
			gfx_fill_rect(cx + x, cy + y, 1, 1, color);
			gfx_fill_rect(cx + y, cy + x, 1, 1, color);
			gfx_fill_rect(cx - y, cy + x, 1, 1, color);
			gfx_fill_rect(cx - x, cy + y, 1, 1, color);
			gfx_fill_rect(cx - x, cy - y, 1, 1, color);
			gfx_fill_rect(cx - y, cy - x, 1, 1, color);
			gfx_fill_rect(cx + y, cy - x, 1, 1, color);
			gfx_fill_rect(cx + x, cy - y, 1, 1, color);

			y++;
			if (err <= 0) {
				err += 2 * y + 1;
			}
			if (err > 0) {
				x--;
				err -= 2 * x + 1;
			}
		}
	}
}

void gfx_hline(int x, int y, int len, uint16_t color)
{
	gfx_fill_rect(x, y, len, 1, color);
}

void gfx_vline(int x, int y, int len, uint16_t color)
{
	gfx_fill_rect(x, y, 1, len, color);
}

void gfx_line(int x0, int y0, int x1, int y1, uint16_t color)
{
	int dx = x1 > x0 ? x1 - x0 : x0 - x1;
	int dy = y1 > y0 ? y1 - y0 : y0 - y1;
	int sx = x0 < x1 ? 1 : -1;
	int sy = y0 < y1 ? 1 : -1;
	int err = dx - dy;

	while (1) {
		gfx_fill_rect(x0, y0, 1, 1, color);
		if (x0 == x1 && y0 == y1) break;
		int e2 = 2 * err;
		if (e2 > -dy) { err -= dy; x0 += sx; }
		if (e2 < dx) { err += dx; y0 += sy; }
	}
}

static const uint8_t *get_font_data(char c)
{
	if (c >= 32 && c <= 95) {
		return font_8x16[c - 32];
	} else if (c >= 97 && c <= 122) {
		return font_lower[c - 97];
	} else if (c >= 123 && c <= 125) {
		return font_braces[c - 123];
	}
	return font_8x16[0]; /* Space for unknown */
}

int gfx_draw_char(int x, int y, char c, uint16_t color, uint16_t bg)
{
	const uint8_t *glyph = get_font_data(c);
	int transparent = (color == bg);

	for (int row = 0; row < 16; row++) {
		uint8_t line = glyph[row];
		for (int col = 0; col < 8; col++) {
			if (line & (0x80 >> col)) {
				gfx_fill_rect(x + col, y + row, 1, 1, color);
			} else if (!transparent) {
				gfx_fill_rect(x + col, y + row, 1, 1, bg);
			}
		}
	}
	return 8;
}

int gfx_draw_string(int x, int y, const char *str, uint16_t color, uint16_t bg)
{
	int start_x = x;
	while (*str) {
		if (*str == '\n') {
			x = start_x;
			y += 16;
		} else {
			x += gfx_draw_char(x, y, *str, color, bg);
		}
		str++;
	}
	return x - start_x;
}

void gfx_draw_string_centered(int y, const char *str, uint16_t color, uint16_t bg)
{
	int len = strlen(str) * 8;
	int x = (gfx_screen_width - len) / 2;
	gfx_draw_string(x, y, str, color, bg);
}
